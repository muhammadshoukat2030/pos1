export async function seedPaintShopProducts() {
  console.log("================================================================================");
  console.log("  SEEDING 71 REALISTIC PAINT SHOP PRODUCTS INTO DEVELOPMENT DATABASE");
  console.log("================================================================================\n");

  await mongoose.connect(MONGO_URI);
  console.log("✅ MongoDB Connected Successfully to:", MONGO_URI);

  const dbName = mongoose.connection.name;
  console.log(`🔍 Verified Database Name: "${dbName}"`);

  if (dbName !== "pos") {
    throw new Error(`SAFETY CHECK FAILED: Expected dev database 'pos', but connected to '${dbName}'! Aborting.`);
  }

  // 1. Synchronize Categories
  const categoriesList = [
    "Paint",
    "Wall Preparation",
    "Paint Thinners",
    "Paint Tools & Accessories"
  ];

  console.log("\n--- STEP 1: Synchronizing Paint Categories ---");
  for (const catName of categoriesList) {
    const exists = await Category.findOne({ name: catName });
    if (!exists) {
      await Category.create({ name: catName, isActive: true });
      console.log(`  + Created Category: "${catName}"`);
    } else {
      console.log(`  ✓ Category exists: "${catName}"`);
    }
  }

  // 2. Synchronize Paint Brands
  const paintBrandsList = [
    "Master Paints", "Berger Paints", "Dulux Paints", "Nippon Paints",
    "Jotun Paints", "Brighto Paints", "Diamond Paints", "Happilac Paints",
    "AkzoNobel", "Bosny", "Samurai", "Maple Leaf", "Sika",
    "National Chemicals", "Crown", "Harris", "Stanley", "Ingco",
    "Master Tools", "Tolsen", "3M", "Norton"
  ];

  console.log("\n--- STEP 2: Synchronizing Paint Brands ---");
  for (const bName of paintBrandsList) {
    const exists = await Brand.findOne({ name: bName });
    if (!exists) {
      await Brand.create({ name: bName, isActive: true });
      console.log(`  + Created Brand: "${bName}"`);
    } else {
      console.log(`  ✓ Brand exists: "${bName}"`);
    }
  }

  // 3. Upsert Paint Shop Products
  console.log("\n--- STEP 3: Inserting 71 Paint Shop Products ---");
  let insertedCount = 0;
  let updatedCount = 0;

  for (let i = 0; i < paintShopProductsData.length; i++) {
    const pData = paintShopProductsData[i];
    const indexNum = i + 1;

    let existing = await Product.findOne({
      $or: [
        { barcode: pData.barcode },
        { sku: pData.sku },
        { stockID: pData.stockID }
      ]
    });

    if (existing) {
      Object.assign(existing, pData);
      existing.brand = pData.brandName;
      await existing.save();
      updatedCount++;
      console.log(`  [${String(indexNum).padStart(2, "0")}/71] 🔄 Updated: "${existing.itemName}" (${existing.sku})`);
    } else {
      const newProd = await Product.create({
        ...pData,
        brand: pData.brandName
      });
      existing = newProd;
      insertedCount++;
      console.log(`  [${String(indexNum).padStart(2, "0")}/71] ➕ Inserted: "${newProd.itemName}" (${newProd.sku})`);
    }

    // Ensure ProductBatch exists for lot tracking
    const batchNum = `BAT-${pData.sku}`;
    let batch = await ProductBatch.findOne({ batchNumber: batchNum });
    if (!batch) {
      await ProductBatch.create({
        productId: existing._id,
        batchNumber: batchNum,
        quantityReceived: pData.totalProduct,
        quantityRemaining: pData.remaining,
        costPrice: pData.costPrice,
        salePrice: pData.salePrice,
        expiryDate: pData.expiryDate,
        status: "Active",
        notes: `Seed lot batch for ${existing.itemName}`
      });
    } else {
      batch.quantityRemaining = pData.remaining;
      batch.costPrice = pData.costPrice;
      batch.salePrice = pData.salePrice;
      batch.expiryDate = pData.expiryDate;
      await batch.save();
    }
  }

  console.log(`\n✅ Finished Seeding: ${insertedCount} newly inserted, ${updatedCount} updated.`);

  // 4. Verification Check
  console.log("\n--- STEP 4: Paint Shop Verification ---");
  const seededBarcodes = paintShopProductsData.map(p => p.barcode);
  const foundPaintProducts = await Product.find({ barcode: { $in: seededBarcodes } }).lean();
  console.log(`📦 Seeded Paint Products in DB: ${foundPaintProducts.length} of ${paintShopProductsData.length}`);

  if (foundPaintProducts.length !== paintShopProductsData.length) {
    throw new Error(`Expected exactly ${paintShopProductsData.length} paint products, found ${foundPaintProducts.length}!`);
  }

  const totalInDb = await Product.countDocuments();
  console.log(`📦 Total Products in Store Catalog: ${totalInDb} (71 Existing + ${foundPaintProducts.length} Paint = ${totalInDb})`);

  // Subcategory distribution
  const subcatDist = {};
  for (const p of foundPaintProducts) {
    const sub = p.subcategory || p.category;
    subcatDist[sub] = (subcatDist[sub] || 0) + 1;
  }
  console.log("\n📊 Paint Subcategory Breakdown:");
  for (const [sub, cnt] of Object.entries(subcatDist)) {
    console.log(`   • ${sub.padEnd(25)}: ${cnt} products`);
  }

  // Low stock check
  const lowStockPaint = foundPaintProducts.filter(p => p.remaining <= p.minStockAlert);
  console.log(`\n⚠️ Low Stock Alert Paint Items: ${lowStockPaint.length} products`);
  lowStockPaint.forEach(p => console.log(`   • ${p.itemName} (Stock: ${p.remaining} ${p.unit}, Alert: ${p.minStockAlert})`));

  console.log("\n================================================================================");
  console.log("  SUCCESS! PAINT SHOP TESTING DATASET DEPLOYED DIRECTLY TO DATABASE");
  console.log("================================================================================\n");

  await mongoose.disconnect();
}

if (process.argv[1] && process.argv[1].includes("seed_paint_shop_products")) {
  seedPaintShopProducts().catch(err => {
    console.error("❌ Seed Script Error:", err);
    process.exit(1);
  });
}
