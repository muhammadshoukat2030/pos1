export async function seedWeldonProducts() {
  try {
    console.log("================================================================================");
    console.log("  SEEDING 34 WELDON PAINT SHOP PRODUCTS (30 COLOURED VARIANTS + 4 NON-COLOUR)");
    console.log("================================================================================");

    if (mongoose.connection.readyState !== 1) {
      await mongoose.connect(MONGO_URI);
      console.log(`Connected to MongoDB: ${MONGO_URI}`);
    }

    // 1. Ensure Brand 'Weldon' exists in Brand collection
    let weldonBrand = await Brand.findOne({ name: "Weldon" });
    if (!weldonBrand) {
      weldonBrand = await Brand.create({
        name: "Weldon",
        description: "Weldon Paints - Premium Architectural, Industrial & Decorative Coatings",
        isActive: true
      });
      console.log("✅ Created Brand: Weldon");
    } else {
      console.log("ℹ️ Brand 'Weldon' already exists.");
    }

    // 2. Remove any previously created Weldon products to ensure clean seed idempotence
    const deleteRes = await Product.deleteMany({
      $or: [
        { brandName: "Weldon" },
        { brand: "Weldon" },
        { sku: { $regex: /^WL-/ } },
        { barcode: { $regex: /^89670040/ } }
      ]
    });
    console.log(`🧹 Cleaned up ${deleteRes.deletedCount} previous Weldon items.`);

    // 3. Clean up batches for Weldon products
    await ProductBatch.deleteMany({ batchNumber: { $regex: /^BAT-WL-/ } });

    // 4. Insert 34 Weldon products
    let insertedCount = 0;
    const insertedBatches = [];

    for (const prodData of weldonPaintProductsData) {
      const createdProd = await Product.create({
        ...prodData,
        brandName: "Weldon",
        brand: "Weldon"
      });

      // Create initial batch
      const batchRecord = {
        productId: createdProd._id,
        batchNumber: `BAT-${prodData.sku}`,
        quantityReceived: prodData.totalProduct,
        quantityRemaining: prodData.remaining,
        costPrice: prodData.costPrice,
        salePrice: prodData.salePrice,
        purchaseDate: new Date(),
        expiryDate: null,
        status: "Active",
        notes: `Initial lot batch for ${createdProd.itemName}`
      };
      insertedBatches.push(batchRecord);
      insertedCount++;
    }

    if (insertedBatches.length > 0) {
      await ProductBatch.insertMany(insertedBatches);
      console.log(`✅ Created ${insertedBatches.length} corresponding ProductBatch lot records.`);
    }

    const totalInDb = await Product.countDocuments();
    const weldonInDb = await Product.countDocuments({ brandName: "Weldon" });
    const colouredWeldonInDb = await Product.countDocuments({ brandName: "Weldon", isPaint: true });
    const nonColourWeldonInDb = await Product.countDocuments({ brandName: "Weldon", isPaint: false });

    console.log("\n--- SEEDING COMPLETED SUCCESSFULLY ---");
    console.log(`• Total Store Catalog Count: ${totalInDb}`);
    console.log(`• Total Weldon Products: ${weldonInDb}`);
    console.log(`• Coloured Weldon Products (All with unique Colour Name & Code): ${colouredWeldonInDb}`);
    console.log(`• Non-Colour Weldon Products (Thinner, Putty, Tools): ${nonColourWeldonInDb}`);
    console.log("================================================================================\n");

    return { insertedCount, totalInDb, weldonInDb };
  } catch (err) {
    console.error("❌ Error seeding Weldon products:", err);
    throw err;
  }
}

// Only execute when run directly from command line
if (process.argv[1] && process.argv[1].includes("seed_weldon_paint_products.js")) {
  seedWeldonProducts()
    .then(() => {
      mongoose.disconnect();
      process.exit(0);
    })
    .catch((err) => {
      console.error(err);
      mongoose.disconnect();
      process.exit(1);
    });
}
